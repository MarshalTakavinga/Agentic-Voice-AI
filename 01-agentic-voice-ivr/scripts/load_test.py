"""Concurrent-call load test against one or more running IVR replicas.

Each virtual caller runs a full verified balance check (4 HTTP requests). Turns are sent to the
replicas round-robin, so with two or more targets every call only succeeds if the replicas share
session state. Writes evals/load_report.md.

    python scripts/load_test.py --targets http://localhost:8001,http://localhost:8002 \\
        --calls 500 --concurrency 50 --label "2 replicas + Redis"
"""

from __future__ import annotations

import argparse
import asyncio
import os
import platform
import statistics
import time
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parent.parent
ACCOUNTS = [("10000001", "1234", "$89.99"), ("10000002", "4321", "$42.50")]


def pct(values: list[float], p: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    return ordered[min(len(ordered) - 1, round(p / 100 * (len(ordered) - 1)))]


async def one_call(client, targets, n, headers, latencies, outcomes) -> None:
    account, pin, expected = ACCOUNTS[n % len(ACCOUNTS)]
    steps = [None, "what's my balance", account, pin]  # None = start the call
    call_id, reply = None, ""
    try:
        for i, text in enumerate(steps):
            base = targets[(n + i) % len(targets)]  # each turn may land on a different replica
            started = time.perf_counter()
            if text is None:
                resp = await client.post(f"{base}/v1/calls", json={}, headers=headers)
            else:
                resp = await client.post(
                    f"{base}/v1/calls/{call_id}/turns", json={"text": text}, headers=headers
                )
            latencies.append((time.perf_counter() - started) * 1000)
            if resp.status_code not in (200, 201):
                outcomes.append(f"http_{resp.status_code}")
                return
            body = resp.json()
            call_id, reply = body["call_id"], body["reply"]
        outcomes.append("ok" if expected in reply else "wrong_answer")
    except httpx.HTTPError as exc:
        outcomes.append(type(exc).__name__)


async def run(targets, calls, concurrency, api_key):
    headers = {"X-API-Key": api_key}
    latencies: list[float] = []
    outcomes: list[str] = []
    limits = httpx.Limits(max_connections=concurrency, max_keepalive_connections=concurrency)
    async with httpx.AsyncClient(timeout=10, limits=limits) as client:
        sem = asyncio.Semaphore(concurrency)

        async def guarded(n):
            async with sem:
                await one_call(client, targets, n, headers, latencies, outcomes)

        started = time.perf_counter()
        await asyncio.gather(*(guarded(n) for n in range(calls)))
        wall = time.perf_counter() - started
    return latencies, outcomes, wall


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--targets", default="http://localhost:8000")
    parser.add_argument("--calls", type=int, default=200)
    parser.add_argument("--concurrency", type=int, default=20)
    parser.add_argument("--label", default="")
    parser.add_argument("--api-key", default=os.environ.get("IVR_API_KEY", "change-me-local-only"))
    parser.add_argument("--report", default=str(ROOT / "evals" / "load_report.md"))
    parser.add_argument("--append", action="store_true", help="add a row to an existing report")
    args = parser.parse_args()
    targets = [t.rstrip("/") for t in args.targets.split(",")]

    latencies, outcomes, wall = asyncio.run(
        run(targets, args.calls, args.concurrency, args.api_key)
    )
    ok = outcomes.count("ok")
    failures = {o: outcomes.count(o) for o in sorted(set(outcomes)) if o != "ok"}
    row = (
        f"| {args.label or ', '.join(targets)} | {len(targets)} | {args.calls} | "
        f"{args.concurrency} | {ok}/{args.calls} | {failures or '—'} | "
        f"{len(latencies) / wall:,.0f} | {statistics.median(latencies):.1f} | "
        f"{pct(latencies, 95):.1f} | {pct(latencies, 99):.1f} |"
    )
    path = Path(args.report)
    if not args.append or not path.exists():
        header = [
            "# Load test report",
            "",
            "Generated by `scripts/load_test.py`. Each call is a full verified balance check "
            "(start, intent, account, PIN = 4 requests); turns go to the replicas round-robin.",
            f"Host: {platform.system()} {platform.machine()}, {os.cpu_count()} vCPU, "
            f"Python {platform.python_version()}; client and servers on the same machine, rules "
            "NLU, mock adapters. These numbers describe this setup only, not production capacity.",
            "",
            "| Setup | Replicas | Calls | Concurrency | Completed correctly | Failures | "
            "Requests/s | p50 ms | p95 ms | p99 ms |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
        path.write_text("\n".join(header) + "\n")
    with path.open("a") as fh:
        fh.write(row + "\n")
    print(row)
    return 0 if ok == args.calls else 1


if __name__ == "__main__":
    raise SystemExit(main())
